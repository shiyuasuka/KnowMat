"""
Node for performing data extraction from the paper text.

This node constructs a combined prompt consisting of a system prompt and a
user prompt and passes it to the ``extraction_extractor`` from
:mod:`knowmat.extractors`. The system prompt is generated by
:func:`knowmat.prompt_generator.generate_system_prompt` and can be modified by
the sub-field detection and evaluation agents via ``state['updated_prompt']``.

Primary path uses TrustCall tool extraction. A conservative raw-JSON fallback
is kept for providers with unstable tool-call compatibility.
"""

import json
import logging
import re
from pathlib import Path
from typing import Any, Dict

from knowmat.extractors import CompositionList, extraction_extractor, get_llm
from knowmat.prompt_generator import generate_system_prompt, generate_user_prompt
from knowmat.states import KnowMatState
from knowmat.app_config import settings

logger = logging.getLogger(__name__)


def _persist_paper_text(path_str: Any, paper_text: str) -> None:
    """Best-effort persistence of enriched paper text back to markdown."""
    if not path_str:
        return
    try:
        out_path = Path(str(path_str))
        out_path.parent.mkdir(parents=True, exist_ok=True)
        out_path.write_text(paper_text, encoding="utf-8")
    except OSError as exc:
        logger.warning("Could not persist enriched paper text to %s: %s", path_str, exc)


def _flatten_message_content(content: Any) -> str:
    """Best-effort conversion from chat content blocks into plain text."""
    if isinstance(content, str):
        return content
    if isinstance(content, list):
        parts = []
        for block in content:
            if isinstance(block, str):
                parts.append(block)
            elif isinstance(block, dict):
                parts.append(str(block.get("text") or block.get("content") or ""))
            else:
                parts.append(str(block))
        return "\n".join(part for part in parts if part).strip()
    return str(content or "")


def _extract_json_object_text(text: str) -> str:
    """Extract the first valid JSON object from free-form model output."""
    payload = str(text or "").strip()
    if payload.startswith("```"):
        payload = re.sub(r"^```(?:json)?\s*", "", payload)
        payload = re.sub(r"\s*```$", "", payload)
    try:
        json.loads(payload)
        return payload
    except Exception:
        pass

    decoder = json.JSONDecoder()
    for match in re.finditer(r"\{", payload):
        try:
            obj, _ = decoder.raw_decode(payload[match.start():])
        except Exception:
            continue
        if isinstance(obj, dict):
            return json.dumps(obj, ensure_ascii=False)
    raise ValueError("Could not locate a valid JSON object in fallback response.")


_COMPACT_FALLBACK_SYSTEM = (
    "You are a materials-science extraction engine. Extract database-ready "
    "structured data from the paper text into ONE JSON object.\n\n"
    "Output schema (return EXACTLY this shape, no prose, no markdown fences):\n"
    "{\n"
    '  "Paper_Metadata": {"Paper_Title": "...", "DOI": "... or null"},\n'
    '  "Paper_Routing": {"base_material": "Metals|Ceramics_Inorganic|Polymers|Composites|Organic_Small_Molecules",\n'
    '                     "application": "Structural|Functional",\n'
    '                     "research_paradigm": "Experimental|Pure_Simulation|Hybrid"},\n'
    '  "compositions": [ {\n'
    '      "Sample_ID": "...", "Role": "Target|Variant|Reference|Comparator",\n'
    '      "Data_Nature": "Experimental|Computed|Literature_Experimental|Literature_Computed",\n'
    '      "Composition": {...}, "Processing": {...}, "Structure": {...},\n'
    '      "Properties": [ {"Property_Name": "...", "Value_Numeric": 0, "Unit": "...",\n'
    '                       "Data_Source": "text|table|image|image_digitized|unknown",\n'
    '                       "Data_Nature": "Experimental", "Note": "..."} ]\n'
    "  } ]\n"
    "}\n\n"
    "CRITICAL — the top-level list MUST be named \"compositions\" (NOT \"items\").\n"
    "Split rules: each distinct composition / heat-treatment / aging time / "
    "thermal-exposure duration / parametric-sweep value / coating layer / "
    "computed (FEM/DFT/CALPHAD) case = a SEPARATE entry. Keep different test "
    "temperatures on the SAME unchanged specimen as ONE entry with multiple Properties.\n"
    "Faithful to source: never invent values; ranges→Value_Range with Value null; "
    "inequalities→Value null + Note; omit fields not mentioned (do not emit null-filled objects).\n"
    "Figure blocks: '> [Figure N AI Description]' prose is CONTEXT ONLY (do not extract numbers). "
    "'> [Figure N VLM-digitized]' blocks ARE extractable — when you take a value from one, set "
    'Data_Source="image_digitized" and Note="estimated from chart (VLM-digitized), not exact". '
    "Prefer text/table/caption values over digitized estimates for the same quantity."
)


def _invoke_plain_json_fallback(full_prompt: str, compact_user: str | None = None) -> Dict[str, Any]:
    """Fallback path for providers that fail structured tool calling.

    When *compact_user* is provided, use a much shorter system+user prompt
    (core schema + split/faithfulness rules only) instead of the full ~22k-token
    template.  Long papers frequently exhaust the model's generation budget
    under the full prompt and return only Paper_Metadata; the compact prompt
    leaves far more room to actually emit the compositions list.
    """
    llm = get_llm(agent_type="extraction")
    if compact_user is not None:
        messages = [
            {"role": "system", "content": _COMPACT_FALLBACK_SYSTEM},
            {"role": "user", "content": compact_user},
            {"role": "user", "content": "Return raw JSON only. Do not call any tool. "
                                        "Top-level list key MUST be \"compositions\"."},
        ]
        response = llm.invoke(messages)
    else:
        fallback_prompt = (
            full_prompt
            + "\n\nIMPORTANT: Do not call any tool."
            + "\nReturn raw JSON only."
            + "\nReturn exactly one JSON object with top-level key `compositions`."
        )
        response = llm.invoke(fallback_prompt)
    content = _flatten_message_content(getattr(response, "content", response))
    payload = _extract_json_object_text(content)
    model = CompositionList.model_validate_json(payload)
    return json.loads(model.model_dump_json())


def extract_data(state: KnowMatState) -> Dict[str, Any]:
    """Perform the main LLM extraction and return the structured data."""
    import time as _time

    paper_text = state.get("paper_text", "")
    original_paper_text = paper_text
    paper_text_path = state.get("paper_text_path")
    routing_supplements = state.get("routing_supplements", "")
    paper_routing = state.get("paper_routing") or {}

    # Stage 2: inject multimodal figure descriptions into paper_text before extraction
    # Uses Approach C: CLIP alignment + VLM with context
    if settings.figure_description_enabled:
        ocr_items = state.get("ocr_items") or []
        if ocr_items:
            from knowmat.pdf.figure_describer import inject_figure_descriptions
            logger.info("Injecting figure descriptions (Approach C: VLM+CLIP)...")
            t0 = _time.time()
            try:
                _output_dir = state.get("output_dir") or ""
                if not _output_dir and paper_text_path:
                    _output_dir = str(Path(paper_text_path).parent.parent)
                _paper_id = ""
                if _output_dir:
                    _paper_id = Path(_output_dir).name
                paper_text = inject_figure_descriptions(
                    paper_text, ocr_items,
                    paper_id=_paper_id, output_dir=_output_dir,
                )
                elapsed = _time.time() - t0
                logger.info("✓ Figure descriptions injected in %.1fs.", elapsed)
                print(f"   Figure descriptions: {elapsed:.1f}s")
            except Exception as exc:
                logger.warning("Figure description injection failed: %s", exc, exc_info=True)

    if paper_text != original_paper_text:
        _persist_paper_text(paper_text_path, paper_text)

    system_prompt = generate_system_prompt(routing_supplements=routing_supplements)

    user_prompt = generate_user_prompt(
        paper_text,
        target_base_material=paper_routing.get("base_material", ""),
        target_application=paper_routing.get("application", ""),
        target_research_paradigm=paper_routing.get("research_paradigm", ""),
        target_patch_tags=", ".join(paper_routing.get("patch_tags", [])),
    )
    input_chars = len(system_prompt) + len(user_prompt)
    print(f"   Extraction input: ~{input_chars // 3} tokens")
    messages = [
        {"role": "system", "content": system_prompt},
        {"role": "user", "content": user_prompt},
        {"role": "user", "content": "Provide your response using the tool."},
    ]
    full_prompt = system_prompt + "\n\n" + user_prompt + "\n\n" + (
        "Provide your response using the tool."
    )

    structured_error: Exception | None = None
    t_extract = _time.time()
    try:
        result = extraction_extractor.invoke({"messages": messages})
    except Exception as exc:
        structured_error = exc
        _is_int_overflow = "integer exceeds 64-bit range" in str(exc).lower()
        if _is_int_overflow:
            logger.warning(
                "Structured extraction hit integer overflow; "
                "skipping structured retries, jumping to raw-JSON fallback. Error: %s",
                exc,
            )
            result = None
        else:
            logger.warning(
                "Structured extraction with role-separated messages failed; "
                "falling back to legacy prompt. Error: %s",
                exc,
            )
            try:
                result = extraction_extractor.invoke(full_prompt)
            except Exception as exc2:
                logger.warning("Legacy structured extraction also failed: %s", exc2)
                result = None

    responses = (result or {}).get("responses") or []
    if not responses and not (structured_error and "integer exceeds 64-bit range" in str(structured_error).lower()):
        print(f"   Extraction attempt 1: {_time.time() - t_extract:.1f}s (no responses, retrying)")
        try:
            fallback_result = extraction_extractor.invoke(full_prompt)
        except Exception as exc:
            if structured_error is None:
                structured_error = exc
            else:
                logger.warning("Structured fallback returned no responses: %s", exc)
            fallback_result = None
        responses = (fallback_result or {}).get("responses") or []
    extraction_elapsed = _time.time() - t_extract
    print(f"   Extraction LLM call: {extraction_elapsed:.1f}s")

    if not responses:
        logger.warning(
            "Tool-based extraction returned no structured responses; "
            "attempting raw-JSON fallback."
        )
        # Build a compact user message: routing hints + the (already
        # figure-enriched) paper text, WITHOUT the ~22k-token step-by-step
        # template.  This frees generation budget so long papers can actually
        # emit the compositions list instead of stopping after Paper_Metadata.
        _rt = paper_routing or {}
        compact_user = (
            "Routing hints (may be empty): "
            f"base_material={_rt.get('base_material','')}, "
            f"application={_rt.get('application','')}, "
            f"research_paradigm={_rt.get('research_paradigm','')}\n\n"
            "=== PAPER TEXT START ===\n"
            f"{paper_text}\n"
            "=== PAPER TEXT END ==="
        )
        try:
            extracted_dict = _invoke_plain_json_fallback(full_prompt, compact_user=compact_user)
            return {"latest_extracted_data": extracted_dict, "paper_text": paper_text}
        except Exception as compact_exc:
            logger.warning("Compact fallback failed (%s); trying full-prompt fallback.", compact_exc)
            try:
                extracted_dict = _invoke_plain_json_fallback(full_prompt)
                return {"latest_extracted_data": extracted_dict, "paper_text": paper_text}
            except Exception as fallback_exc:
                if structured_error is not None:
                    raise RuntimeError(
                        "Extraction failed in both structured and raw-JSON modes: "
                        f"{structured_error}; fallback={fallback_exc}"
                    ) from fallback_exc
                raise

    response = responses[0]
    if isinstance(response, CompositionList):
        extracted_dict = json.loads(response.model_dump_json())
    else:
        extracted_dict = response
    return {"latest_extracted_data": extracted_dict, "paper_text": paper_text}
